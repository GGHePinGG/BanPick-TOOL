(function () {
  'use strict';

  var CSBP = (window.CSBP = window.CSBP || {});

  function isZh() {
    return CSBP.I18n ? CSBP.I18n.isZh() : true;
  }

  function L(zh, en) {
    return CSBP.I18n ? CSBP.I18n.L(zh, en) : zh;
  }

  function playerName(state, idx) {
    if (idx === null || idx === undefined) return '—';
    return state.players[idx] || L('选手 ' + (idx + 1), 'Player ' + (idx + 1));
  }

  function mapLabel(map) {
    return isZh() ? map.cn + ' ' + map.en : map.en;
  }

  function buildReport(state) {
    var lines = [];
    var capA = state.captains ? playerName(state, state.captains.A) : L('未知', 'Unknown');
    var capB = state.captains ? playerName(state, state.captains.B) : L('未知', 'Unknown');

    lines.push((CSBP.Games && CSBP.Games.current ? CSBP.Games.current().label : 'CS2') + L(' 在线 BP 战报', ' Online BP Report'));
    lines.push(L('赛制：BO' + state.config.series + ' ｜ 图池：' + state.config.pool.length + ' 张',
      'Format: BO' + state.config.series + ' | Map pool: ' + state.config.pool.length));
    lines.push('--------------------------------');

    ['A', 'B'].forEach(function (side) {
      var cap = side === 'A' ? capA : capB;
      var names = state.draft.picks
        .filter(function (p) { return p.side === side; })
        .map(function (p) { return playerName(state, p.player); });
      lines.push(L('队伍 ' + side + '（队长：' + cap + '）', 'Team ' + side + ' (Captain: ' + cap + ')'));
      lines.push('  ' + (names.length ? names.join(' · ') : '—'));
    });

    lines.push('--------------------------------');
    lines.push(L('比赛地图', 'Match maps'));

    CSBP.MapBP.decidedMaps(state).forEach(function (item, i) {
      var map = CSBP.Maps.get(item.mapId);
      var tag;
      if (item.type === 'decider') {
        tag = state.config.series === 1 ? L('比赛地图', 'Match map') : L('决胜图', 'Decider');
      } else {
        tag = L(item.side + ' 队选', 'Team ' + item.side + ' pick');
      }
      var side = state.mapbp.sides[item.mapId];
      if (side) tag += L(' · 选边 ' + side, ' · Side ' + side);
      lines.push((i + 1) + '. ' + mapLabel(map) + ' (' + tag + ')');
    });

    lines.push('--------------------------------');
    lines.push(L('由 球球 生成', 'Generated by Qiuqiu'));
    return lines.join('\n');
  }

  function copyText(text) {
    if (navigator.clipboard && window.isSecureContext) {
      return navigator.clipboard.writeText(text).then(function () {
        return true;
      }).catch(function () {
        return legacyCopy(text);
      });
    }
    return Promise.resolve(legacyCopy(text));
  }

  function legacyCopy(text) {
    try {
      var ta = document.createElement('textarea');
      ta.value = text;
      ta.setAttribute('readonly', 'readonly');
      ta.style.position = 'fixed';
      ta.style.top = '-1000px';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      var ok = document.execCommand('copy');
      document.body.removeChild(ta);
      return ok;
    } catch (e) {
      return false;
    }
  }

  CSBP.Share = {
    buildReport: buildReport,
    copy: copyText
  };
})();
